# Compiles the backend's vertex shaders to vs_2_0 bytecode with fxc from the Windows SDK, so the DLL needs no shader
# compiler at run time:
#   src/ddraw9/skin.hlsl (both variants) -> src/ddraw9/skin_shaders.inc
#   src/ddraw9/ground.hlsl               -> src/ddraw9/ground_shaders.inc
#   src/ddraw9/smaa.hlsl (vs_3_0/ps_3_0, low/medium/high presets) -> src/ddraw9/smaa_shaders.inc
#   src/ddraw9/sharp.hlsl (ps_2_a, the world's sharp bilinear sampling) -> src/ddraw9/sharp_shaders.inc
# Usage: python tools/gen_shaders.py   (FXC = path to fxc.exe if it is not found in the Windows Kits folder)
import glob, os, subprocess, sys, tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paths  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Variants: (array name, fxc defines[, profile, entry point]); the default is vs_2_0 / main.
SMAA_PRESETS = [('Low', 'SMAA_PRESET_LOW'), ('Medium', 'SMAA_PRESET_MEDIUM'), ('High', 'SMAA_PRESET_HIGH')]
SMAA_VARIANTS = [
    ('kSmaaEdgeVS', ['/D', 'SMAA_PRESET_LOW=1'], 'vs_3_0', 'EdgeVS'),
    ('kSmaaBlendVS', ['/D', 'SMAA_PRESET_LOW=1'], 'vs_3_0', 'BlendVS'),
    ('kSmaaBlendPS', ['/D', 'SMAA_PRESET_LOW=1'], 'ps_3_0', 'BlendPS'),
] + [variant for preset, define in SMAA_PRESETS for variant in (
    (f'kSmaaEdgePS{preset}', ['/D', f'{define}=1'], 'ps_3_0', 'EdgePS'),
    (f'kSmaaWeightVS{preset}', ['/D', f'{define}=1'], 'vs_3_0', 'WeightVS'),
    (f'kSmaaWeightPS{preset}', ['/D', f'{define}=1'], 'ps_3_0', 'WeightPS'),
)]
SHADERS = [
    ('skin.hlsl', 'skin_shaders.inc', [('kSkinShader', []), ('kSkinShaderDiffuse', ['/D', 'DIFFUSE=1'])]),
    ('ground.hlsl', 'ground_shaders.inc', [('kGroundShader', [])]),
    ('smaa.hlsl', 'smaa_shaders.inc', SMAA_VARIANTS),
    ('sharp.hlsl', 'sharp_shaders.inc', [('kSharpShader', [], 'ps_2_a', 'main')]),
]


def find_fxc():
    if os.environ.get('FXC'):
        return os.environ['FXC']
    found = sorted(glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\fxc.exe'))
    if not found:
        sys.exit('fxc.exe not found; set FXC')
    return found[-1]


def compile_variant(fxc, source, name, defines, profile='vs_2_0', entry='main'):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'shader.h')
        cmd = [fxc, '/nologo', '/T', profile, '/E', entry, '/O3', '/Vn', name, '/Fh', out, *defines, source]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(f'fxc failed for {name}:\n{result.stdout}{result.stderr}')
        with open(out) as f:
            text = f.read()
    # Keep the instruction listing fxc writes as a comment (for review), the byte array as is.
    return text.replace('const BYTE', 'static const BYTE')


def main():
    fxc = find_fxc()
    for source, output, variants in SHADERS:
        src = os.path.join(paths.DDRAW9, source)
        out = os.path.join(paths.DDRAW9, output)
        parts = [f'// Generated by tools/gen_shaders.py from src/ddraw9/{source} -- do not edit by hand.\n']
        for variant in variants:
            parts.append(compile_variant(fxc, src, *variant))
        with open(out, 'w', newline='\n') as f:
            f.write('\n'.join(parts))
        print(f'wrote {os.path.relpath(out, ROOT)}')


if __name__ == '__main__':
    main()
