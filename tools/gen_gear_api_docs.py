#!/usr/bin/env python3
"""Writes docs/GearApi.md, the Lua API reference, from the LuaLS definitions in gear/meta/*.lua.

    python tools/gen_gear_api_docs.py            write docs/GearApi.md
    python tools/gen_gear_api_docs.py --check    fail if the file is not what the definitions produce
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gear_meta  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
META = os.path.join(ROOT, 'gear', 'meta')
OUT = os.path.join(ROOT, 'docs', 'GearApi.md')
HEAD = os.path.join(ROOT, 'docs', 'GearApi.head.md')   # the hand-written part in front of the generated reference

NAMESPACE_PREFIXES = ('gear', 'os')


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def anchor(title):
    # GitHub's heading ids: lower case, punctuation other than - and _ dropped, spaces to -.
    return re.sub(r'[^\w\- ]', '', title.lower()).replace(' ', '-')


def sig(model, fn):
    cls = model.classes.get(fn.owner) if fn.owner else None
    if cls is not None:
        prefix = (cls.path or cls.name) + (':' if fn.colon else '.')
    else:
        prefix = ''
    args = fn.args.strip()
    text = f'{prefix}{fn.name}({args})'
    rets = [r[0] for r in fn.returns]
    if rets:
        text += ' -> ' + ', '.join(rets)
    return text


def render_func(model, fn, out):
    out.append(f'#### `{sig(model, fn)}`')
    out.append('')
    if fn.deprecated:
        out.append(f'*Not available:* {fn.deprecated}')
        out.append('')
    if fn.desc:
        out.append(fn.desc)
        out.append('')
    if fn.overloads:
        out.append('Forms:')
        out.append('')
        for o in fn.overloads:
            out.append(f'- `{o}`')
        out.append('')
    if any(p.desc or p.type for p in fn.params) and not fn.deprecated:
        for p in fn.params:
            opt = ' (optional)' if p.optional else ''
            d = f' - {p.desc}' if p.desc else ''
            out.append(f'- `{p.name}`: `{p.type.rstrip("?")}`{opt}{d}')
    if fn.returns and not fn.deprecated:
        for typ, name, desc in fn.returns:
            label = f'`{name}` ' if name else ''
            d = f' - {desc}' if desc else ''
            out.append(f'- returns {label}`{typ}`{d}')
    if (fn.params and any(p.desc or p.type for p in fn.params)) or fn.returns:
        out.append('')


def render_class(model, cls, out):
    out.append(f'### {cls.name}')
    out.append('')
    if cls.path:
        if cls.path.split('.')[0] in NAMESPACE_PREFIXES:
            out.append(f'Reached as `{cls.path}`.')
        else:
            out.append(f'Written `{cls.path}` in the signatures.')
        out.append('')
    if cls.parent:
        out.append(f'Includes everything of `{cls.parent}`.')
        out.append('')
    if cls.desc:
        out.append(cls.desc)
        out.append('')
    if cls.fields:
        out.append('| Field | Type | |')
        out.append('|---|---|---|')
        for f in cls.fields:
            opt = ' (optional)' if f.optional else ''
            out.append(f'| `{f.name}` | `{cell(f.type.rstrip("?"))}` | {cell(f.desc)}{opt} |')
        out.append('')


def render_alias(a, out):
    out.append(f'### {a.name}')
    out.append('')
    if a.desc:
        out.append(a.desc)
        out.append('')
    if a.values:
        out.append('| Value | |')
        out.append('|---|---|')
        for v, d in a.values:
            out.append(f'| `{cell(v)}` | {cell(d)} |')
        out.append('')
    elif a.type:
        out.append(f'`{a.type}`')
        out.append('')


def generate():
    model = gear_meta.parse(META)
    out = ['<!-- Generated by tools/gen_gear_api_docs.py from gear/meta/*.lua. Do not edit: change the annotations. -->', '']
    if os.path.exists(HEAD):
        with open(HEAD, encoding='utf-8') as f:
            out.append(f.read().rstrip('\n'))
        out.append('')
    out.append('## Contents')
    out.append('')
    for sec in model.sections:
        out.append(f'- [{sec.title}](#{anchor(sec.title)})')
    out.append('')
    for sec in model.sections:
        out.append(f'## {sec.title}')
        out.append('')
        if sec.intro:
            out.append(gear_meta.join_doc(sec.intro))
            out.append('')
        for item in sec.items:
            if isinstance(item, gear_meta.Cls):
                render_class(model, item, out)
            elif isinstance(item, gear_meta.Alias):
                render_alias(item, out)
            elif isinstance(item, gear_meta.Func):
                render_func(model, item, out)
    text = '\n'.join(out).rstrip('\n') + '\n'
    return re.sub(r'\n{3,}', '\n\n', text)


def main():
    text = generate()
    if '--check' in sys.argv:
        current = ''
        if os.path.exists(OUT):
            with open(OUT, encoding='utf-8', newline='') as f:
                current = f.read().replace('\r\n', '\n')
        if current != text:
            print('docs/GearApi.md is out of date: run python tools/gen_gear_api_docs.py')
            return 1
        print('docs/GearApi.md is up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
