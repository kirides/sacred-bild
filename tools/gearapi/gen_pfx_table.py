# Emits src/gear/engine/gear_pfx.inc: for every effect type 0x300..0x49D, the size of the particle system object cObjectFX's setup
# (ENG 0x5A0C50) allocates for it (0: the type makes no particle system), and the case (system class) number.
# The setup indexes a byte table (0x5A3570) by type - 0x300 and jumps through a table (0x5A3294); a case's code pushes the object size and
# calls operator new (0x849842). Gear scans a system object for texture handles only inside this size.
# Usage: python tools/gearapi/gen_pfx_table.py   (SACRED_ENG as for gen_sigs.py)
import os, re, struct, sys
sys.path[:0] = [os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), *p)) for p in [(), ('..',), ('..', 'sigs'), ('..', 'gearapi')]]  # tools/, tools/sigs, tools/gearapi
import eng
import paths

BYTE_TABLE = 0x5A3570
JUMP_TABLE = 0x5A3294
NEW = 0x849842
FIRST, COUNT = 0x300, 0x19E
DEFAULT_CASE = 0xB6          # "goto default": no effect


def case_size(target):
    code = eng.rd(target, 96)
    pending = None
    for ins in eng.md.disasm(code, target):
        if ins.mnemonic == 'push' and ins.op_str.startswith('0x'):
            pending = int(ins.op_str, 16)
        elif ins.mnemonic == 'call':
            if int(ins.op_str, 16) == NEW and pending:
                return pending
        elif ins.mnemonic in ('ret', 'jmp'):
            break
    return 0


def write_doc(rows):
    names = sorted(set(m.group(0).decode() for m in re.finditer(rb'(?:PARTICLE|FX)_[A-Z0-9_]+\.TGA', eng.IMG)))
    out = ['# Skill effect types and textures (generated)', '',
           'Generated by `tools/gearapi/gen_pfx_table.py` from the English `Sacred.exe`; do not edit. How to use them: [GearPfx.md](GearPfx.md).', '',
           '## Effect types', '',
           'Every effect an art or spell makes is an object of one type from 0x300 to 0x49D. `class` is the particle system class the game makes for it',
           '(a number of its own, the case of the effect setup at 0x5A0C50; types with the same class share the code and differ in a constant or two);',
           '`size` is the byte size of that class object. Types without a particle system are left out.', '',
           '| type | decimal | class | size |', '|---|---|---|---|']
    for fx, case, size in rows:
        if size:
            out.append(f'| 0x{fx:X} | {fx} | {case} | {size} |')
    out += ['', '## Textures', '',
            'The names `textures` of a variant can use (the game own list; the effect classes load them by these names).', '']
    out += ['- `' + n + '`' for n in names]
    path = paths.GEAR_PFX_TYPES_MD
    with open(path, 'w', newline=chr(10)) as f:
        f.write(chr(10).join(out) + chr(10))


def main():
    cases = {}
    rows = []
    for i in range(COUNT):
        case = eng.rd(BYTE_TABLE + i, 1)[0]
        if case == DEFAULT_CASE:
            rows.append((FIRST + i, 0, 0))
            continue
        if case not in cases:
            target = eng.u32(JUMP_TABLE + case * 4)
            cases[case] = (target, case_size(target))
        rows.append((FIRST + i, case, cases[case][1]))
    out = ['// Generated by tools/gearapi/gen_pfx_table.py -- do not edit by hand.',
           '// Effect type 0x300 + index: the particle system class (the switch case of ENG 0x5A0C50) and the size of its object (0: none).',
           'struct FxClass { uint16_t cls; uint32_t size; };',
           'static const FxClass kFxClasses[0x19E] = {']
    for fx, case, size in rows:
        out.append(f'    {{{case}, {size}}}, // 0x{fx:X}')
    out.append('};')
    path = paths.GEAR_PFX
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    write_doc(rows)
    missing = [hex(fx) for fx, case, size in rows if case and not size]
    print('types with a system:', sum(1 for r in rows if r[1]), ' classes:', len(cases), ' without size:', missing)


if __name__ == '__main__':
    main()
