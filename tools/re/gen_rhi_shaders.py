# Compiles the NVRHI renderer's HLSL (src/bild/rhi/shaders/*.hlsl, src/bild/ddrawrhi/shaders/*.hlsl, docs/NvrhiRenderer.md) offline, so the DLL needs no
# shader compiler at run time: DXIL (shader model 6.0) for Direct3D 12 with the Windows SDK's dxc, which signs it, and
# SPIR-V for Vulkan with the Vulkan SDK's dxc (the Windows SDK's has no SPIR-V back end). Each shader file becomes
# <name>_shaders.inc next to it with one byte array per entry point and API: k<Name>Dxil, k<Name>Spirv.
#
# Registers map to Vulkan bindings as NVRHI's default VulkanBindingOffsets (t 0, s 128, b 256, u 384). Clip space needs no
# change: NVRHI's Vulkan backend sets a negative-height viewport (VKViewportWithDXCoords), so y points up in both APIs.
#
# Usage: python tools/re/gen_rhi_shaders.py   (DXC_DXIL / DXC_SPIRV = dxc.exe paths if not found)
import glob, os, re, subprocess, sys, tempfile

sys.path[:0] = [os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))]
import paths  # noqa: E402

SHADER_DIRS = [os.path.join(paths.BILD, 'rhi', 'shaders'), os.path.join(paths.BILD, 'ddrawrhi', 'shaders')]
SPACES = 4  # register spaces given Vulkan binding shifts

# Entry points per file: (array name, profile, entry, defines).
SHADERS = {
    'test.hlsl': [
        ('TestVS', 'vs_6_0', 'vsMain', []),
        ('TestPS', 'ps_6_0', 'psMain', []),
    ],
    'ff.hlsl': [
        ('FixedVS', 'vs_6_0', 'vsMain', []),
        ('FixedPS', 'ps_6_0', 'psMain', []),
    ],
    'blit.hlsl': [
        ('BlitVS', 'vs_6_0', 'vsMain', []),
        ('BlitCopyPS', 'ps_6_0', 'psCopy', []),
        ('BlitFillPS', 'ps_6_0', 'psFill', []),
    ],
}


def find_dxc(env, patterns, what):
    if os.environ.get(env):
        return os.environ[env]
    for pattern in patterns:
        found = sorted(glob.glob(pattern))
        if found:
            return found[-1]
    sys.exit(f'dxc.exe ({what}) not found; set {env}')


def dxc_dxil():
    return find_dxc('DXC_DXIL', [r'C:\Program Files (x86)\Windows Kits\10\bin\10.*\x64\dxc.exe'], 'Windows SDK')


def dxc_spirv():
    sdk = os.environ.get('VULKAN_SDK', r'C:\VulkanSDK\*')
    return find_dxc('DXC_SPIRV', [os.path.join(sdk, 'Bin', 'dxc.exe'), r'C:\VulkanSDK\*\Bin\dxc.exe'], 'Vulkan SDK')


def spirv_args(profile):
    args = ['-spirv', '-fspv-target-env=vulkan1.3']
    for space in range(SPACES):
        args += ['-fvk-t-shift', '0', str(space), '-fvk-s-shift', '128', str(space),
                 '-fvk-b-shift', '256', str(space), '-fvk-u-shift', '384', str(space)]
    return args


def compile_one(dxc, source, profile, entry, defines, extra):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'out.bin')
        cmd = [dxc, '-nologo', '-T', profile, '-E', entry, '-O3', '-HV', '2021', '-Fo', out,
               *[f'-D{d}' for d in defines], *extra, source]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit(f'dxc failed: {" ".join(cmd)}\n{result.stdout}{result.stderr}')
        with open(out, 'rb') as f:
            return f.read()


def array(name, data):
    lines = [f'static const unsigned char {name}[{len(data)}] = {{']
    for i in range(0, len(data), 24):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    dxil, spirv = dxc_dxil(), dxc_spirv()
    for source, entries in SHADERS.items():
        src = next(os.path.join(d, source) for d in SHADER_DIRS if os.path.exists(os.path.join(d, source)))
        out = re.sub(r'\.hlsl$', '_shaders.inc', src)
        rel = os.path.relpath(src, paths.ROOT).replace(os.sep, '/')
        parts = [f'// Generated by tools/re/gen_rhi_shaders.py from {rel} -- do not edit by hand.', '#pragma once', '']
        for name, profile, entry, defines in entries:
            parts.append(array(f'k{name}Dxil', compile_one(dxil, src, profile, entry, defines, [])))
            parts.append(array(f'k{name}Spirv', compile_one(spirv, src, profile, entry, defines, spirv_args(profile))))
            parts.append('')
        with open(out, 'w', newline='\n') as f:
            f.write('\n'.join(parts))
        print(f'wrote {os.path.relpath(out, paths.ROOT)}')


if __name__ == '__main__':
    main()
